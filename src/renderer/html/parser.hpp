// الملف: تعريف محلل إتش تي إم إل
// الغرض: إعلان الواجهة العامة للمحلل.
//
// ما هو المحلل؟
// المحلل مسؤول عن تحويل نص إتش تي إم إل إلى شجرة عقد.
// يأخذ النص كمدخل، ويُعيد مؤشراً إلى العقدة الجذرية.
//
// ما مستوى الدقة؟
// هذا محلل مبسّط، لا يتبع مواصفات رابطة الشبكة العالمية
// بالكامل. يكفي لعرض صفحات إتش تي إم إل البسيطة.
//
// متى نستبدله؟
// عند الانتقال إلى المرحلة الأولى من المشروع، سنستبدله
// بمحلل مواصفات كامل، مثل مكتبة ليكسبور.
// =============================================================

// استيراد نوع العقدة، لأن المحلل يُعيد شجرة منها.
#include "renderer/html/node.hpp"

namespace honeybee::html {

// نتيجة تحليل نص إتش تي إم إل.
struct ParseResult {
    NodePtr root;             // جذر الشجرة.
    bool success = true;      // هل نجح التحليل؟
    std::string error;        // رسالة خطأ إن فشل التحليل.
};

// تحليل نص إتش تي إم إل وإنتاج شجرة عقد.
//
// المعامل: النص الخام لصفحة إتش تي إم إل.
// المُخرج: نتيجة التحليل، مع الجذر والعلامات.
//
// في حال النص الفارغ، تُعاد شجرة فيها عقدة جذر فقط.
ParseResult parse(const std::string& html);

}  //
