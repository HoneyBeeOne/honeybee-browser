// =============================================================
// الملف: تعريف عقدة شجرة العناصر
// الغرض: إعلان بنية العقدة الواحدة في شجرة تحليل إتش تي إم إل.
//
// ما هي العقدة؟
// العقدة هي وحدة بناء في الشجرة. كل وسم في إتش تي إم إل
// يُنتج عقدة من نوع عنصر، وكل نص بين وسمين يُنتج عقدة من
// نوع نص. والعقدة قد تحتوي على عقد أخرى، فتتشكل شجرة كاملة
// تمثل الصفحة.
//
// تعريفات الوسوم المستخدمة في هذا الملف وفي الملفات التالية:
// وسم الفقرة (p): هو الوسم الذي يمثل فقرة نصية.
// وسم الرابط (a): هو الوسم الذي يمثل رابطاً قابلاً للنقر.
// وسم التمييز (b): هو الوسم الذي يميز نصاً عن غيره.
// وسم التوكيد (strong): هو الوسم الذي يؤكد على نص بقوة.
// وسم التمييز البسيط (em): هو الوسم الذي يميز نصاً بشكل أخف.
// وسم العنوان الأول (h1): هو الوسم الذي يمثل أكبر عناوين الصفحة.
// وسم العنوان الثاني (h2): هو الوسم الذي يمثل العنوان التالي في الحجم.
// وسم القائمة (ul): هو الوسم الذي يمثل قائمة نقطية.
// وسم القائمة المرقمة (ol): هو الوسم الذي يمثل قائمة مرقمة.
// وسم العنصر (li): هو الوسم الذي يمثل عنصراً داخل قائمة.
// وسم الحاوية (div): هو الوسم الذي يمثل حاوية عامة.
// وسم النطاق (span): هو الوسم الذي يمثل نطاقاً عاماً داخل سطر.
// وسم الفاصل (br): هو الوسم الذي يمثل فاصل سطر.
//
// مثال توضيحي:
// إذا كان لدينا وسم الفقرة، وداخله نص، ثم وسم التمييز،
// وداخله نص آخر، فإن الشجرة تكون كالتالي:
// عنصر من نوع الفقرة.
//   عقدة نص، نصها الأول.
//   عنصر من نوع التمييز.
//     عقدة نص، نصها الثاني.
// =============================================================

// استيراد الحاويات المعيارية:
// نص، لتخزين نص العقد.
// متجه، لتخزين الأبناء بالترتيب.
// خريطة، لتخزين السمات.
// مؤشر ذكي مشترك، لتخزين الأبناء بأمان.
#include <map>
#include <memory>
#include <string>
#include <vector>

namespace honeybee::html {

// نوع العقدة: إما عنصر، أو نص.
enum class NodeType {
    Element,   // عقدة عنصر: تمثل وسماً.
    Text       // عقدة نص: تمثل نصاً مجرداً.
};

// بنية العقدة الواحدة.
struct Node {
    // نوع العقدة.
    NodeType type = NodeType::Element;

    // اسم الوسم في حالة العنصر.
    // ويبقى فارغاً في حالة النص.
    std::string tag;

    // نص العقدة في حالة النص.
    // ويبقى فارغاً في حالة العنصر.
    std::string text;

    // سمات العنصر في حالة العنصر، مثل سمة الرابط.
    std::map<std::string, std::string> attributes;

    // أبناء العقدة: قائمة مرتبة من العقد الفرعية.
    std::vector<std::shared_ptr<Node>> children;

    // هل هذه العقدة من نوع نص؟
    bool is_text() const {
        return type == NodeType::Text;
    }

    // هل هذه العقدة من نوع عنصر؟
    bool is_element() const {
        return type == NodeType::Element;
    }
};

// اسم مختصر لمؤشر العقدة.
using NodePtr = std::shared_ptr<Node>;

}  //
