// الملف: تعريف العارض
// الغرض: إعلان الصنف المسؤول عن تحويل شجرة العقد إلى عناصر
// واجهة جي تي كي.
//
// ما هو العارض؟
// العارض يأخذ شجرة عقد ناتجة من المحلل، ويبني منها عنصر
// واجهة واحداً قابلاً للعرض في النافذة.
//
// كيف يعمل؟
// نمر على كل عقدة في الشجرة.
// إن كانت عقدة نص، نُنتج نصاً عادياً.
// وإن كانت عقدة عنصر، نُنتج عنصر واجهة مناسباً لاسم الوسم.
// ونُضيف الأبناء إلى الأب، فنبني الشجرة المرئية تدريجياً.
//
// تعريفات الوسوم المستخدمة في هذا الملف:
// وسم العنوان الأول (h1): العنوان الأكبر حجماً.
// وسم العنوان الثاني (h2): العنوان التالي في الحجم.
// وسم العنوان الثالث (h3): العنوان التالي في الحجم.
// وسم العنوان الرابع (h4): العنوان التالي في الحجم.
// وسم العنوان الخامس (h5): العنوان التالي في الحجم.
// وسم العنوان السادس (h6): العنوان الأصغر حجماً.
// وسم الفقرة (p): فقرة نصية.
// وسم الرابط (a): رابط قابل للنقر.
// وسم القائمة (ul): قائمة نقطية.
// وسم القائمة المرقمة (ol): قائمة مرقمة.
// وسم العنصر (li): عنصر داخل قائمة.
// وسم الحاوية (div): حاوية عامة.
// وسم النطاق (span): نطاق داخل سطر.
// وسم الفاصل (br): فاصل سطر.
// وسم التوكيد (strong): نص عريض بقوة.
// وسم التمييز (b): نص عريض.
// وسم التمييز البسيط (em): نص مائل.
// =============================================================

// استيراد مكتبة الواجهة، لأن العارض يُنتج عنصر جي تي كي.
#include <gtkmm.h>

// استيراد نوع العقدة، لأن العارض يستقبل شجرة منها.
#include "renderer/html/node.hpp"

namespace honeybee::renderer {

// الصنف: العارض.
//
// كل دالة فيه ساكنة، لأن العارض لا يحفظ حالة بين الاستدعاءات.
// هذا يُسهّل استخدامه، ويمنع الأخطاء الناتجة عن حالة مشتركة.
class Renderer {
public:
    // يحوّل شجرة العقد إلى عنصر واجهة واحد.
    //
    // المعامل: مؤشر إلى العقدة الجذرية للشجرة.
    // المُخرج: مؤشر إلى عنصر جي تي كي يحتوي على العرض الكامل.
    //
    // إن كانت الشجرة فارغة، تُعاد حاوية عمودية فارغة.
    static Gtk::Widget* render(const html::NodePtr& root);

private:
    // يحوّل عقدة واحدة إلى عنصر واجهة.
    // تُستخدم هذه الدالة داخلياً، وتُستدعى بشكل متكرر
    // لكل عقدة ولأبنائها.
    static Gtk::Widget* render_node(const html::NodePtr& node);

    // يحوّل عقدة نص إلى عنصر نصي.
    static Gtk::Widget* render_text(const html::NodePtr& node);

    // يحوّل عقدة عنصر إلى عنصر واجهة مناسب لاسم الوسم.
    static Gtk::Widget* render_element(const html::NodePtr& node);

    // يُنشئ حاوية عمودية تحتوي على كل أبناء العقدة.
    static Gtk::Widget* render_children(const html::NodePtr& node);
};

}  //
