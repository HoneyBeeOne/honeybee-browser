#pragma once

// =============================================================
// الملف: تعريف الجالب اللاتزامني
// الغرض: إعلان الصنف الذي يجلب الموارد في خيط منفصل.
//
// ما وظيفة هذا الصنف؟
// جلب الموارد من الشبكة دون تجميد الواجهة. يبقى الخيط
// الرئيسي مستجيباً، ويتحمّل الخيط الخلفي عناء الانتظار.
//
// لماذا نحتاجه؟
// دالة الجلب في وحدة الشبكة متزامنة، أي أنها تُجمّد الخيط
// الذي تستدعيها فيه حتى انتهاء الجلب. لو استدعيناها من
// الخيط الرئيسي، حيث حلقة الواجهة، لتجمّدت الواجهة كلها.
//
// الحل:
// تشغيل الجلب في خيط منفصل، ثم إبلاغ الخيط الرئيسي عند
// الانتهاء عبر الموزِّع من مكتبة جِلب.
// =============================================================

// الاستيرادات اللازمة:
// دالة معيارية لتخزين ردود النداء.
// نص معياري لتمثيل الروابط.
// خيط معياري لتشغيل الجلب.
// الموزِّع من جِلب للإبلاغ الآمن بين الخيوط.
// بنية الاستجابة من وحدة الشبكة.
#include <functional>
#include <string>
#include <thread>

#include <glibmm/dispatcher.h>

#include "net/response.hpp"

// الصنف: الجالب اللاتزامني.
//
// طريقة الاستخدام:
// يُنشأ كائن واحد، ويُستدعى له الجلب مع رابط ورد نداء.
// ورد النداء يُنفَّذ في الخيط الرئيسي بعد انتهاء الجلب.
//
// قيود مهمة:
// لا يُسمح بجلبتين متزامنتين. أي جلب جديد ينتظر انتهاء
// الجلب السابق أولاً. والصنف ليس آمناً للاستخدام من عدة
// خيوط، فيُستعمل من الخيط الرئيسي فقط.
//
// كيف يعمل؟
// عند استدعاء الجلب:
// يُحفظ رد النداء.
// يُشغَّل خيط جديد ينفّذ جلب الشبكة.
// عند انتهاء الجلب في الخيط الخلفي:
// تُحفظ النتيجة في العضو المخصص.
// تُطلق إشارة الموزِّع.
// والموزِّع ينفّذ رد النداء في الخيط الرئيسي بأمان.
class AsyncFetcher {
public:
    // نوع رد النداء: دالة تستقبل الاستجابة، ولا تُعيد شيئاً.
    // وتُنفَّذ في الخيط الرئيسي.
    using Callback =
        std::function<void(honeybee::net::Response)>;

    // المُنشئ: يهيّئ الموزِّع ويربطه بالمنطق.
    AsyncFetcher();

    // الهادم: ينتظر انتهاء الخيط قبل التدمير.
    ~AsyncFetcher();

    // منع النسخ والنقل، لأن الصنف يملك موارد.
    AsyncFetcher(const AsyncFetcher&) = delete;
    AsyncFetcher& operator=(const AsyncFetcher&) = delete;

    // يبدأ جلب الرابط في خيط منفصل.
    // المعاملات: الرابط، ورد النداء الذي يُنفَّذ عند الانتهاء.
    void fetch(const std::string& url, Callback on_done);

private:
    // جسر الإبلاغ بين الخيط الخلفي والخيط الرئيسي.
    Glib::Dispatcher m_dispatcher;

    // نتيجة الجلب الأخيرة.
    honeybee::net::Response m_result;

    // رد النداء المُقدَّم من المستخدم.
    Callback m_callback;

    // خيط الجلب.
    std::thread m_thread;
};
