#pragma once

// =============================================================
// الملف: async_fetcher.hpp
// الغرض: إعلان صنف AsyncFetcher
//
// ما هو AsyncFetcher؟
// صنف يجلب الموارد من الشبكة في خيط منفصل، دون حجب
// الخيط الرئيسي للواجهة.
//
// لماذا نحتاجه؟
// دالة net::fetch() متزامنة، أي أنها تحجب الخيط الذي
// تستدعيها فيه حتى انتهاء الجلب. لو استدعيناها من الخيط
// الرئيسي (حيث حلقة GTK)، ستتجمّد الواجهة كلها.
//
// الحل: تشغيل الجلب في خيط منفصل، ثم إبلاغ الخيط الرئيسي
// عند الانتهاء عبر Glib::Dispatcher.
// =============================================================

// استيراد المكتبات اللازمة.
//
// functional: لتخزين الرد (callback) ككائن قابل للاستدعاء.
// string: لتمثيل الرابط.
// thread: لتشغيل الجلب في خيط منفصل.
// glibmm/dispatcher.h: للإبلاغ الآمن من خيط إلى آخر.
// net/response.hpp: لبنية Response التي تُعاد من الجلب.

#include <functional>
#include <string>
#include <thread>

#include <glibmm/dispatcher.h>

#include "net/response.hpp"

// صنف AsyncFetcher: يجلب الموارد من الشبكة في خيط منفصل.
//
// الاستخدام:
//   AsyncFetcher fetcher;
//   fetcher.fetch("https://example.com",
//                 [](honeybee::net::Response r) {
//                     // هذا الرد يُنفَّذ في الخيط الرئيسي.
//                 });
//
// قيود مهمة:
//   - لا يُسمح باستدعاء fetch() قبل انتهاء الجلب السابق.
//     لو حدث ذلك، ننتظر انتهاء الخيط القديم أولاً.
//   - الصنف ليس آمناً للاستخدام من عدة خيوط في وقت واحد.
//     استخدمه من الخيط الرئيسي فقط.
//
// كيف يعمل؟
//   1. عند استدعاء fetch():
//      - نحفظ الرد المُقدَّم من المستخدم.
//      - نُشغّل خيطاً جديداً يشغّل net::fetch().
//   2. عند انتهاء الجلب في الخيط الخلفي:
//      - نحفظ النتيجة في m_result.
//      - نُطلق m_dispatcher.emit().
//   3. الـ Dispatcher يُنفّذ الرد في الخيط الرئيسي، حيث
//      حلقة GTK، فيُحدّث الواجهة بأمان.
class AsyncFetcher {
public:
    // نوع الرد: دالة تستقبل Response، ولا تُعيد شيئاً.
    // الرد يُنفَّذ في الخيط الرئيسي.
    using Callback =
        std::function<void(honeybee::net::Response)>;

    // المُنشئ: يُهيّئ الـ Dispatcher ويربطه بالمنطق.
    AsyncFetcher();

    // الهادم: ينتظر انتهاء الخيط قبل التدمير، لتفادي
    // استخدام كائن مُدمَّر من خيط لا يزال يعمل.
    ~AsyncFetcher();

    // منع النسخ والنقل، لأن الصنف يملك موارد (خيط،
    // dispatcher). نسخها قد يُسبّب أخطاء خطيرة.
    AsyncFetcher(const AsyncFetcher&) = delete;
    AsyncFetcher& operator=(const AsyncFetcher&) = delete;

    // يبدأ جلب الرابط في خيط منفصل.
    //
    // المعاملات:
    //   - url: الرابط الكامل (يبدأ بـ http:// أو https://).
    //   - on_done: الرد الذي يُنفَّذ في الخيط الرئيسي بعد
    //     انتهاء الجلب، مع نتيجة الجلب.
    //
    // السلوك:
    //   - إذا كان هناك خيط سابق لا يزال يعمل، ننتظر انتهاءه.
    //   - يُشغَّل خيط جديد للجلب.
    void fetch(const std::string& url, Callback on_done);

private:
    // جسر الإبلاغ بين الخيط الخلفي والخيط الرئيسي.
    // يُنشأ في الخيط الرئيسي، فتُنفَّذ إشارته هناك.
    Glib::Dispatcher m_dispatcher;

    // نتيجة الجلب الأخيرة.
    // يكتبها الخيط الخلفي، ويقرأها الخيط الرئيسي بعد الإشارة.
    honeybee::net::Response m_result;

    // الرد المُقدَّم من المستخدم. يُحفظ هنا لأن الـ Dispatcher
    // يحتاج الوصول إليه عند تنفيذ الإشارة.
    Callback m_callback;

    // خيط الجلب. يُشغَّل عند كل استدعاء لـ fetch().
    std::thread m_thread;
};
