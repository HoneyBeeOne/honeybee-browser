#pragma once

// =============================================================
// الملف: window.hpp
// الغرض: إعلان صنف HoneyBeeWindow
//
// ما هو HoneyBeeWindow؟
// الصنف الرئيسي للنافذة. يرث من Gtk::Window، ويحتوي على
// كل عناصر الواجهة: شريط الأدوات، شريط العنوان، منطقة العرض،
// وشريط الحالة.
//
// ما مسؤوليته؟
//   - بناء الواجهة في المُنشئ.
//   - ربط الإشارات (signals) بالمعالجات (handlers).
//   - تحديث الواجهة عند وصول نتائج من الشبكة.
//
// علاقته بباقي المكونات:
//   - يستخدم honeybee::is_valid_url() للتحقق من الرابط.
//   - يستخدم honeybee::net::fetch() (عبر AsyncFetcher) للجلب.
//   - يستخدم honeybee::version_string() لطباعة الإصدار.
// =============================================================

// استيراد gtkmm، وهو غلاف ++C لـ GTK.
// يوفّر كل عناصر الواجهة التي نستخدمها: Window، Box، Button،
// Entry، Label، إلخ.
#include <gtkmm.h>

// استيراد إعلان AsyncFetcher، لأن النافذة تحتوي عليه كعضو.
#include "browser/async_fetcher.hpp"

// صنف النافذة الرئيسية. يرث من Gtk::Window، فيرث كل خصائص
// النافذة العادية (عنوان، حجم، إغلاق، إلخ).
class HoneyBeeWindow : public Gtk::Window {
public:
    // المُنشئ: يبني كل عناصر الواجهة ويربط الإشارات.
    HoneyBeeWindow();

private:
    // ----------------------------------------------------------
    // المعالجات (handlers)
    // ----------------------------------------------------------

    // معالجة ضغط Enter في شريط العنوان.
    //   1. تتحقق من الرابط بـ is_valid_url().
    //   2. إذا كان صحيحاً، تبدأ جلبه عبر AsyncFetcher.
    //   3. إذا كان خاطئاً، تُحدّث شريط الحالة برسالة رفض.
    void on_url_activated();

    // ----------------------------------------------------------
    // أعضاء الواجهة (widgets)
    // ----------------------------------------------------------

    // الحاوية الرئيسية: تخطيط عمودي.
    // تحتوي على ثلاثة عناصر من الأعلى إلى الأسفل:
    //   1. شريط الأدوات (m_toolbar_box).
    //   2. منطقة العرض (m_label).
    //   3. شريط الحالة (m_status_bar).
    Gtk::Box m_root_box;

    // شريط الأدوات: تخطيط أفقي.
    // يحتوي على أزرار التنقل + شريط العنوان.
    Gtk::Box m_toolbar_box;

    // زر الرجوع. معطّل حالياً حتى تُنفَّذ المهمة 77.
    Gtk::Button m_back_button;

    // زر التقدم. معطّل حالياً حتى تُنفَّذ المهمة 77.
    Gtk::Button m_forward_button;

    // زر إعادة التحميل. معطّل حالياً حتى تُنفَّذ المهمة 77.
    Gtk::Button m_reload_button;

    // شريط العنوان: حقل نص أحادي السطر.
    // عند ضغط Enter، تُطلَق إشارة activate() المرتبطة بـ
    // on_url_activated().
    Gtk::Entry m_url_bar;

    // منطقة العرض: نص مؤقت لعرض محتوى الصفحة.
    // في المرحلة الحالية، نعرض أول 500 حرف من المحتوى.
    // في المراحل التالية، سيُستبدَل بمحرك عرض حقيقي.
    Gtk::Label m_label;

    // شريط الحالة: تخطيط أفقي.
    // يحتوي على رسالة الحالة + رقم الإصدار.
    Gtk::Box m_status_bar;

    // نص الحالة: يُحدَّث عند كل تغيير (جارٍ الجلب، تم، فشل).
    Gtk::Label m_status_label;

    // رقم الإصدار: يُعرض في يمين شريط الحالة. ثابت.
    Gtk::Label m_version_label;

    // ----------------------------------------------------------
    // أعضاء المنطق
    // ----------------------------------------------------------

    // جالب لاتزامني: يُشغّل net::fetch() في خيط منفصل،
    // ويُبلِّغ الخيط الرئيسي عند الانتهاء.
    // هذا يمنع تجمّد الواجهة أثناء الجلب.
    AsyncFetcher m_async_fetcher;
};
