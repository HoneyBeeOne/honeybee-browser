// استيراد إعلان الصنف نفسه.
#include "window.hpp"

// استيراد دالة version_string() لعرض رقم الإصدار.
#include "base/version.hpp"

// استيراد دالة is_valid_url() للتحقق من الرابط.
#include "base/url.hpp"

// =============================================================
// المُنشئ: بناء الواجهة
// -------------------------------------------------------------
// المُنشئ مسؤول عن:
//   1. ضبط خصائص النافذة (العنوان، الحجم).
//   2. بناء كل عناصر الواجهة (widgets).
//   3. ربط الإشارات بالمعالجات.
//   4. تجميع العناصر في الشجرة (layout tree).
//
// قائمة التهيئة (initializer list) ضرورية لأن بعض الأعضاء
// تحتاج معاملات في المُنشئ (مثل: اتجاه Box).
// =============================================================

HoneyBeeWindow::HoneyBeeWindow()
    : m_root_box(Gtk::Orientation::VERTICAL),
      m_toolbar_box(Gtk::Orientation::HORIZONTAL),
      m_status_bar(Gtk::Orientation::HORIZONTAL) {

    // ---------------------------------------------------------
    // الخطوة الأولى: ضبط خصائص النافذة
    // ---------------------------------------------------------
    set_title("HoneyBee Browser — متصفح");
    set_default_size(1024, 768);

    // ---------------------------------------------------------
    // الخطوة الثانية: إعداد أزرار التنقل
    // ---------------------------------------------------------
    // كل زر له:
    //   - تسمية (label): رمز يمثل الوظيفة.
    //   - تلميح (tooltip): نص يظهر عند المرور بالماوس.
    //   - حالة (sensitive): معطّل الآن، سيُفعَّل لاحقاً.

    m_back_button.set_label("←");
    m_forward_button.set_label("→");
    m_reload_button.set_label("↻");

    m_back_button.set_tooltip_text("رجوع");
    m_forward_button.set_tooltip_text("تقدم");
    m_reload_button.set_tooltip_text("إعادة التحميل");

    // تعطيل الأزرار مؤقتاً لأن منطقها لم يُكتب بعد.
    // (المهمة #77 مسؤولة عن تفعيلها.)
    m_back_button.set_sensitive(false);
    m_forward_button.set_sensitive(false);
    m_reload_button.set_sensitive(false);

    // ---------------------------------------------------------
    // الخطوة الثالثة: إعداد شريط العنوان
    // ---------------------------------------------------------

    // نص مؤقت يظهر عندما يكون الحقل فارغاً.
    m_url_bar.set_placeholder_text("أدخل عنوان الموقع");

    // يمتد أفقياً ليملأ المساحة المتبقية من شريط الأدوات.
    m_url_bar.set_hexpand(true);

    // ربط إشارة activate() (تُطلَق عند ضغط Enter) بمعالجنا.
    // اللامبدا تلتقط this للوصول إلى الدالة العضو.
    m_url_bar.signal_activate().connect(
        [this]() { on_url_activated(); });

    // ---------------------------------------------------------
    // الخطوة الرابعة: تجميع شريط الأدوات
    // ---------------------------------------------------------
    // نستخدم Box أفقي لتجميع العناصر بجانب بعضها:
    //   [←] [→] [↻] [شريط العنوان ....................]

    m_toolbar_box.set_spacing(6);   // مسافة بين العناصر
    m_toolbar_box.set_margin(6);    // هامش خارجي حول الشريط

    m_toolbar_box.append(m_back_button);
    m_toolbar_box.append(m_forward_button);
    m_toolbar_box.append(m_reload_button);
    m_toolbar_box.append(m_url_bar);

    // ---------------------------------------------------------
    // الخطوة الخامسة: إعداد منطقة العرض
    // ---------------------------------------------------------
    // في المرحلة الحالية، نستخدم Label نصي لعرض محتوى الصفحة.
    // لاحقاً، سيُستبدَل بمحرك عرض حقيقي (GTK DrawingArea).

    // بناء النص الافتراضي بإضافة رقم الإصدار من الدالة.
    // هذا يضمن وجود الإصدار في مكان واحد فقط.
    const std::string label_text =
        "HoneyBee Browser\n\nالمرحلة صفر — الإصدار " +
        honeybee::version_string() +
        "\n\nسيُعرض محتوى الصفحة هنا";

    m_label.set_text(label_text);
    m_label.set_justify(Gtk::Justification::CENTER);
    m_label.set_margin(24);
    m_label.set_vexpand(true);      // يمتد رأسياً

    // ---------------------------------------------------------
    // الخطوة السادسة: إعداد شريط الحالة
    // ---------------------------------------------------------
    // الشريط يتكون من عنصرين:
    //   - m_status_label: رسالة الحالة (يسار).
    //   - m_version_label: رقم الإصدار (يمين).

    m_status_label.set_text("جاهز");

    // نستخدم نفس دالة الإصدار، بادئة بـ "v".
    m_version_label.set_text("v" + honeybee::version_string());

    // hexpand + halign END يدفعان الإصدار إلى أقصى اليمين.
    m_version_label.set_hexpand(true);
    m_version_label.set_halign(Gtk::Align::END);

    m_status_bar.set_margin(6);
    m_status_bar.append(m_status_label);
    m_status_bar.append(m_version_label);

    // ---------------------------------------------------------
    // الخطوة السابعة: التجميع النهائي
    // ---------------------------------------------------------
    // نُضيف العناصر الثلاثة إلى m_root_box من الأعلى للأسفل:
    //   1. m_toolbar_box: شريط الأدوات.
    //   2. m_label: منطقة العرض.
    //   3. m_status_bar: شريط الحالة.

    m_root_box.append(m_toolbar_box);
    m_root_box.append(m_label);
    m_root_box.append(m_status_bar);

    // نُعيّن m_root_box كالابن الوحيد للنافذة.
    set_child(m_root_box);
}

// =============================================================
// on_url_activated(): معالجة ضغط Enter في شريط العنوان
// -------------------------------------------------------------
// المنطق:
//   1. نأخذ النص من شريط العنوان.
//   2. نتحقق من صحته بـ is_valid_url().
//   3. إذا كان خاطئاً: نُحدّث شريط الحالة فوراً ونخرج.
//   4. إذا كان صحيحاً:
//      - نُحدّث شريط الحالة بـ "جارٍ الجلب...".
//      - نُعطّل حقل الإدخال لمنع جلبتين متزامنتين.
//      - نبدأ الجلب في الخيط الخلفي.
//      - في الـ callback (يُنفَّذ في الخيط الرئيسي):
//        * نُعيد تفعيل حقل الإدخال.
//        * إذا فشل الجلب: نعرض رسالة فشل.
//        * إذا نجح: نعرض أول 500 حرف من المحتوى.
// =============================================================

void HoneyBeeWindow::on_url_activated() {
    // الخطوة الأولى: أخذ النص من الحقل.
    const std::string url = m_url_bar.get_text();

    // الخطوة الثانية: التحقق من الرابط.
    if (!honeybee::is_valid_url(url)) {
        // رابط خاطئ: نُحدّث الشريط ونخرج. لا جلب.
        m_status_label.set_text("رابط غير صالح");
        return;
    }

    // الخطوة الثالثة: تجهيز الواجهة للجلب.
    m_status_label.set_text("جارٍ الجلب...");

    // تعطيل الحقل، لأن AsyncFetcher لا يدعم جلبتين متزامنتين.
    m_url_bar.set_sensitive(false);

    // الخطوة الرابعة: بدء الجلب في الخيط الخلفي.
    //
    // اللامبدا تُلتقط بـ [this] للوصول إلى أعضاء النافذة.
    // المعامل r يُمرَّر بالقيمة، لأنه نتيجة جلب واحدة.
    //
    // ملاحظة: هذا الرد يُنفَّذ في الخيط الرئيسي، بفضل
    // Glib::Dispatcher داخل AsyncFetcher. لذا تحديث الواجهة
    // هنا آمن تماماً.
    m_async_fetcher.fetch(url, [this](honeybee::net::Response r) {

        // إعادة تفعيل حقل الإدخال، لتمكين جلب جديد.
        m_url_bar.set_sensitive(true);

        // الخطوة الخامسة: معالجة نتيجة الجلب.

        // حالة الفشل: رمز الحالة ليس 2xx.
        if (!r.success()) {
            m_status_label.set_text(
                "فشل الجلب (رمز الحالة: " +
                std::to_string(r.status_code) + ")");
            return;
        }

        // حالة النجاح: نعرض جزءاً من المحتوى.
        // نقتطع أول 500 حرف فقط، لأن Label لا يصلح للنصوص
        // الطويلة، وقد يُبطئ الواجهة.
        constexpr std::size_t kMaxPreview = 500;
        std::string preview = r.body.substr(0, kMaxPreview);

        // نُنبّه المستخدم أن المحتوى مقتطع.
        if (r.body.size() > kMaxPreview) {
            preview += "\n\n... (اقتُطع المحتوى)";
        }

        // عرض المحتوى في منطقة العرض.
        m_label.set_text(preview);
        m_label.set_justify(Gtk::Justification::LEFT);

        // تحديث شريط الحالة بحجم المحتوى الكامل.
        m_status_label.set_text(
            "تم الجلب: " + std::to_string(r.body.size()) + " بايت");
    });
}
