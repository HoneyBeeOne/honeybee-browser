// =============================================================
// الملف: تنفيذ الجالب اللاتزامني
// الغرض: تنفيذ صنف الجالب اللاتزامني.
//
// هذا الملف يحتوي على ثلاث دوال:
// المُنشئ: يهيّئ الموزِّع ويربطه بالمنطق.
// الهادم: ينتظر انتهاء الخيط قبل التدمير.
// دالة الجلب: تُشغّل الجلب في خيط جديد.
// =============================================================

// استيراد إعلان الصنف نفسه.
#include "browser/async_fetcher.hpp"

// استيراد أداة النقل، لنقل رد النداء بدل نسخه.
#include <utility>

// استيراد دالة الجلب التي سنُشغّلها في الخيط.
#include "net/client.hpp"

// =============================================================
// المُنشئ: تهيئة الموزِّع
//
// الموزِّع هو جسر آمن بين الخيوط. عند إنشائه في الخيط
// الرئيسي، فإن كل إشارة تُطلق منه ستُنفَّذ في نفس الخيط،
// حيث حلقة أحداث الواجهة تعمل.
//
// نربط إشارته بدالة تلتقط هذا الكائن، فتصل إلى رد النداء
// والنتيجة كأعضاء في الكائن.
// =============================================================

AsyncFetcher::AsyncFetcher() {
    // الربط: كل مرة تُطلق إشارة الموزِّع من أي خيط، تُنفَّذ
    // هذه الدالة في الخيط الرئيسي.
    m_dispatcher.connect([this]() {
        // قبل استدعاء رد النداء، نتأكد أنه مُعيَّن.
        if (m_callback) {
            // نستدعي رد النداء المُقدَّم من المستخدم، ونمرّر
            // له نتيجة الجلب المحفوظة.
            m_callback(m_result);
        }
    });
}

// =============================================================
// الهادم: انتظار الخيط قبل التدمير
//
// عند تدمير الكائن، قد يكون الخيط لا يزال يعمل. لو لم
// ننتظره، فسيحاول الوصول إلى أعضاء الكائن بعد تدميرها،
// وهذا خطأ خطير.
//
// الانضمام ينتظر انتهاء الخيط بأمان. والفحص أولاً يتأكد
// أن الخيط قابل للانضمام.
// =============================================================

AsyncFetcher::~AsyncFetcher() {
    // إذا كان الخيط لا يزال يعمل، ننتظره حتى ينتهي.
    if (m_thread.joinable()) {
        m_thread.join();
    }
}

// =============================================================
// دالة الجلب: تشغيل الجلب في خيط منفصل
//
// هذه الدالة تُنفَّذ في الخيط الرئيسي. ومهامها:
// انتظار أي جلب سابق لم ينتهِ بعد.
// حفظ رد النداء الجديد.
// إنشاء خيط جديد يُشغّل جلب الشبكة.
// في الخيط الجديد، إطلاق إشارة الموزِّع عند الانتهاء.
// =============================================================

void AsyncFetcher::fetch(const std::string& url, Callback on_done) {
    // الخطوة الأولى: انتظار الجلب السابق.
    // لو كان هناك خيط لا يزال يعمل، ننتظره حتى ينتهي.
    // هذا يمنع تشغيل جلبين في وقت واحد، ويضمن أن النتيجة
    // ورد النداء لن يُستخدَما من خيطين مختلفين.
    if (m_thread.joinable()) {
        m_thread.join();
    }

    // الخطوة الثانية: حفظ رد النداء الجديد.
    // نستخدم أداة النقل بدل النسخ، لأنها أسرع.
    // رد النداء محفوظ في العضو المخصص، ليستخدمه الموزِّع
    // عند إطلاق الإشارة.
    m_callback = std::move(on_done);

    // الخطوة الثالثة: إنشاء خيط جديد.
    //
    // الدالة الداخلية تلتقط:
    // هذا الكائن: للوصول إلى النتيجة والموزِّع.
    // الرابط بنسخة، لأن مرجع الرابط الأصلي قد ينتهي قبل
    // انتهاء الجلب.
    //
    // ما يحدث داخل الخيط:
    // نُشغّل جلب الشبكة ونحفظ النتيجة في العضو المخصص.
    // نُطلق إشارة الموزِّع، ليُنبَّه الخيط الرئيسي.
    // الإشارة تُجدوَل، ولا تُنفَّذ فوراً. والخيط الرئيسي
    // سينفّذ رد النداء في أول فرصة، حيث حلقة الواجهة.
    m_thread = std::thread([this, url]() {
        m_result = honeybee::net::fetch(url);
        m_dispatcher.emit();
    });
}
