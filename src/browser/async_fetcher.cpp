// =============================================================
// الملف: async_fetcher.cpp
// الغرض: تنفيذ صنف AsyncFetcher
//
// هذا الملف يحتوي على ثلاث دوال:
//   1. المُنشئ: يُهيّئ الـ Dispatcher ويربطه بالمنطق.
//   2. الهادم: ينتظر انتهاء الخيط قبل التدمير.
//   3. fetch(): يُشغّل الجلب في خيط جديد.
// =============================================================

// استيراد إعلان الصنف نفسه.
#include "browser/async_fetcher.hpp"

// استيراد std::move، لنقل الرد بدل نسخه.
#include <utility>

// استيراد دالة net::fetch() التي سنُشغّلها في الخيط.
#include "net/client.hpp"

// =============================================================
// المُنشئ: تهيئة الـ Dispatcher
// -------------------------------------------------------------
// الـ Dispatcher (glibmm::Dispatcher) هو جسر آمن بين الخيوط.
// عند إنشائه في الخيط الرئيسي، فإن كل إشارة تُطلق منه ستُنفَّذ
// في نفس الخيط (الخيط الرئيسي)، حيث حلقة أحداث GTK تعمل.
//
// نربط إشارته بدالة لامبدا (lambda) تلتقط this، فتصل إلى
// m_callback و m_result كأعضاء في الكائن.
// =============================================================

AsyncFetcher::AsyncFetcher() {
    // connect() تربط الإشارة بالدالة.
    // كل مرة يُستدعى m_dispatcher.emit() من أي خيط، تُنفَّذ
    // هذه اللامبدا في الخيط الرئيسي.
    m_dispatcher.connect([this]() {
        // قبل استدعاء الرد، نتأكد أنه مُعيَّن (ليس nullptr).
        // لو لم يُعيَّن (حالة نادرة)، نخرج بهدوء.
        if (m_callback) {
            // نستدعي الرد المُقدَّم من المستخدم، ونمرّر له
            // نتيجة الجلب المحفوظة.
            m_callback(m_result);
        }
    });
}

// =============================================================
// الهادم: انتظار الخيط قبل التدمير
// -------------------------------------------------------------
// عند تدمير الكائن، قد يكون الخيط لا يزال يعمل. لو لم ننتظره،
// فسيحاول الوصول إلى أعضاء الكائن (مثل m_result) بعد تدميرها،
// وهذا خطأ خطير (use-after-free).
//
// join() تنتظر انتهاء الخيط بأمان.
// joinable() تتحقق أولاً أن الخيط قابل للانضمام (يعمل حالياً).
// =============================================================

AsyncFetcher::~AsyncFetcher() {
    // إذا كان الخيط لا يزال يعمل، ننتظره حتى ينتهي.
    if (m_thread.joinable()) {
        m_thread.join();
    }
}

// =============================================================
// fetch(): تشغيل الجلب في خيط منفصل
// -------------------------------------------------------------
// هذه الدالة تُنفَّذ في الخيط الرئيسي (استدعاها المستخدم).
// مهامها:
//   1. انتظار أي جلب سابق لم ينتهِ بعد.
//   2. حفظ الرد الجديد.
//   3. إنشاء خيط جديد يُشغّل net::fetch().
//   4. في الخيط الجديد، إطلاق m_dispatcher.emit() عند الانتهاء.
// =============================================================

void AsyncFetcher::fetch(const std::string& url, Callback on_done) {
    // الخطوة الأولى: انتظار الجلب السابق.
    // لو كان هناك خيط لا يزال يعمل، ننتظره حتى ينتهي.
    // هذا يمنع تشغيل جلبين في وقت واحد، ويضمن أن m_result
    // و m_callback لن يُستخدَما من خيطين مختلفين.
    if (m_thread.joinable()) {
        m_thread.join();
    }

    // الخطوة الثانية: حفظ الرد الجديد.
    // نستخدم std::move لنقل الرد بدل نسخه (أسرع).
    // الرد محفوظ في m_callback، ليستخدمه الـ Dispatcher عند
    // إطلاق الإشارة.
    m_callback = std::move(on_done);

    // الخطوة الثالثة: إنشاء خيط جديد.
    //
    // اللامبدا تلتقط:
    //   - this: للوصول إلى m_result و m_dispatcher.
    //   - url: بنسخة (by value)، لأن مرجع الرابط الأصلي قد
    //     ينتهي قبل انتهاء الجلب.
    //
    // ما يحدث داخل الخيط:
    //   1. نُشغّل net::fetch() ونحفظ النتيجة في m_result.
    //   2. نُطلق m_dispatcher.emit()، ليُنبَّه الخيط الرئيسي.
    //      الإشارة تُجدوَل، ولا تُنفَّذ فوراً. الخيط الرئيسي
    //      سينفّذ الرد في أول فرصة، حيث حلقة GTK.
    m_thread = std::thread([this, url]() {
        m_result = honeybee::net::fetch(url);
        m_dispatcher.emit();
    });
}
